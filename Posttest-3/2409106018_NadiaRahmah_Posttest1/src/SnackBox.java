public class SnackBox {
    String id;
    String namaPaket;
    String isiSnack;
    double harga;

    public SnackBox( String id, String namaPaket, String isiSnack, double harga){
        this.id = id;
        this.namaPaket = namaPaket;
        this.isiSnack = isiSnack;
        this.harga = harga;
    }
}
